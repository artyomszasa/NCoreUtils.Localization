using System.CodeDom.Compiler;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using Microsoft.CodeAnalysis.CSharp;

namespace NCoreUtils.Localization.Generator;

internal static class LocalizerNames
{
    public const string EmptyLocale = "Empty";

    public static string ShortName(string interfaceName)
        => interfaceName.Length > 1 && interfaceName[0] == 'I' && char.IsUpper(interfaceName[1])
            ? interfaceName.Substring(1)
            : interfaceName;

    public static string RawInterface(string interfaceName)
        => "IRaw" + ShortName(interfaceName);

    public static string Factory(string interfaceName)
        => "Default" + ShortName(interfaceName) + "Factory";

    /// <summary>
    /// Name of the locale classes, e.g. <c>HuHU</c> for <c>hu-HU</c> and <c>ZhHansCN</c> for <c>zh-Hans-CN</c>.
    /// </summary>
    public static string Locale(string locale)
        => string.Concat(locale.Split('-').Select(part => char.ToUpperInvariant(part[0]) + part.Substring(1)));
}

internal sealed class LocalizerEmitter
{
    private readonly LocalizerTarget target;

    private readonly List<MergedMember> root;

    private readonly string rawInterface;

    private readonly string typePrefix;

    private readonly IndentedTextWriter writer;

    private LocalizerEmitter(LocalizerTarget target, List<MergedMember> root, TextWriter output)
    {
        this.target = target;
        this.root = root;
        rawInterface = LocalizerNames.RawInterface(target.Name);
        typePrefix = target.Namespace is null ? "global::" : $"global::{target.Namespace}.";
        writer = new(output, "    ");
    }

    public static string Emit(LocalizerTarget target, List<MergedMember> root, IEnumerable<string> locales)
    {
        using var output = new StringWriter { NewLine = "\n" };
        new LocalizerEmitter(target, root, output).EmitFile(locales);
        return output.ToString();
    }

    private void EmitFile(IEnumerable<string> locales)
    {
        writer.WriteLine("// <auto-generated/>");
        writer.WriteLine("#nullable enable");
        writer.WriteLineNoTabs(string.Empty);
        if (target.Namespace is not null)
        {
            writer.WriteLine($"namespace {target.Namespace}");
            OpenBlock();
        }
        EmitRawInterface(root, string.Empty);
        writer.WriteLineNoTabs(string.Empty);
        EmitInterface(root, string.Empty);
        writer.WriteLineNoTabs(string.Empty);
        EmitFactory(locales);
        if (target.Namespace is not null)
        {
            CloseBlock();
        }
    }

    private void EmitRawInterface(List<MergedMember> members, string path)
    {
        writer.WriteLine($"{target.Accessibility} partial interface {rawInterface}{path}");
        OpenBlock();
        foreach (var member in members)
        {
            var type = member.IsObject ? typePrefix + rawInterface + path + "_" + member.Key : "string?";
            writer.WriteLine($"{type} {member.Identifier} {{ get; }}");
        }
        CloseBlock();
        foreach (var member in members.Where(m => m.IsObject))
        {
            writer.WriteLineNoTabs(string.Empty);
            EmitRawInterface(member.Children, path + "_" + member.Key);
        }
    }

    private void EmitInterface(List<MergedMember> members, string path)
    {
        writer.WriteLine($"{target.Accessibility} partial interface {target.Name}{path}");
        OpenBlock();
        writer.WriteLine($"{typePrefix}{rawInterface}{path} RawValues {{ get; }}");
        foreach (var member in members)
        {
            if (member.IsObject)
            {
                writer.WriteLine($"{typePrefix}{target.Name}{path}_{member.Key} {member.Identifier} {{ get; }}");
            }
            else
            {
                writer.WriteLine($"string {member.Identifier} => RawValues.{member.Identifier} ?? {Literal(member.Key)};");
            }
        }
        CloseBlock();
        foreach (var member in members.Where(m => m.IsObject))
        {
            writer.WriteLineNoTabs(string.Empty);
            EmitInterface(member.Children, path + "_" + member.Key);
        }
    }

    private void EmitFactory(IEnumerable<string> locales)
    {
        writer.WriteLine($"{target.Accessibility} sealed partial class {LocalizerNames.Factory(target.Name)}");
        OpenBlock();
        writer.WriteLine($"public {typePrefix}{target.Name} Create()");
        OpenBlock();
        writer.WriteLine("switch (global::System.Globalization.CultureInfo.CurrentCulture.Name)");
        OpenBlock();
        foreach (var locale in locales)
        {
            writer.WriteLine($"case {Literal(locale)}: return {LocalizerNames.Locale(locale)}.Default;");
        }
        writer.WriteLine($"default: return {LocalizerNames.EmptyLocale}.Default;");
        CloseBlock();
        CloseBlock();
        foreach (var locale in locales)
        {
            EmitLocale(locale, LocalizerNames.Locale(locale));
        }
        EmitLocale(null, LocalizerNames.EmptyLocale);
        CloseBlock();
    }

    /// <param name="locale">Locale to emit, <c>null</c> for the empty implementation.</param>
    /// <param name="name">Name of the locale class.</param>
    private void EmitLocale(string? locale, string name)
    {
        writer.WriteLineNoTabs(string.Empty);
        EmitClasses(locale, "Raw" + name, isRaw: true);
        writer.WriteLineNoTabs(string.Empty);
        EmitClasses(locale, name, isRaw: false);
    }

    /// <summary>
    /// Emits the class of the locale, its nested classes are generated for the nested objects defined by the
    /// locale. Other nested objects are served by the empty implementation.
    /// </summary>
    private void EmitClasses(string? locale, string rootClass, bool isRaw)
    {
        writer.WriteLine($"private sealed class {rootClass} : {InterfaceName(isRaw, string.Empty)}");
        OpenBlock();
        EmitClassBody(locale, rootClass, rootClass, root, string.Empty, isRaw);
        EmitNestedClasses(locale, rootClass, root, string.Empty, isRaw);
        CloseBlock();
    }

    private void EmitNestedClasses(string? locale, string rootClass, List<MergedMember> members, string path, bool isRaw)
    {
        foreach (var member in members.Where(m => IsDefined(m, locale)))
        {
            var nestedPath = path + "_" + member.Key;
            var name = rootClass + nestedPath;
            writer.WriteLineNoTabs(string.Empty);
            writer.WriteLine($"internal sealed class {name} : {InterfaceName(isRaw, nestedPath)}");
            OpenBlock();
            EmitClassBody(locale, rootClass, name, member.Children, nestedPath, isRaw);
            CloseBlock();
            EmitNestedClasses(locale, rootClass, member.Children, nestedPath, isRaw);
        }
    }

    private void EmitClassBody(string? locale, string rootClass, string name, List<MergedMember> members, string path, bool isRaw)
    {
        var implemented = InterfaceName(isRaw, path);
        if (isRaw)
        {
            writer.WriteLine($"public static {name} Default {{ get; }} = new {name}();");
            writer.WriteLineNoTabs(string.Empty);
            writer.WriteLine($"private {name}() {{ }}");
            writer.WriteLineNoTabs(string.Empty);
        }
        else
        {
            var rawName = "Raw" + name;
            var rawClass = path.Length == 0 ? rawName : $"Raw{rootClass}.{rawName}";
            writer.WriteLine($"public static {name} Default {{ get; }} = new {name}({rawClass}.Default);");
            writer.WriteLineNoTabs(string.Empty);
            writer.WriteLine($"private readonly {rawClass} rawValues;");
            writer.WriteLineNoTabs(string.Empty);
            writer.WriteLine($"private {name}({rawClass} rawValues) {{ this.rawValues = rawValues; }}");
            writer.WriteLineNoTabs(string.Empty);
            writer.WriteLine($"{InterfaceName(true, path)} {implemented}.RawValues => rawValues;");
        }
        foreach (var member in members)
        {
            if (member.IsObject)
            {
                var nestedPath = path + "_" + member.Key;
                var owner = IsDefined(member, locale)
                    ? rootClass
                    : (isRaw ? "Raw" : string.Empty) + LocalizerNames.EmptyLocale;
                writer.WriteLine($"{InterfaceName(isRaw, nestedPath)} {implemented}.{member.Identifier} => {owner}.{owner}{nestedPath}.Default;");
            }
            else if (isRaw)
            {
                var value = locale is not null && member.Values.TryGetValue(locale, out var entry) ? entry.Value : null;
                writer.WriteLine($"string? {implemented}.{member.Identifier} => {(value is null ? "null" : Literal(value))};");
            }
        }
    }

    private static bool IsDefined(MergedMember member, string? locale)
        => member.IsObject && (locale is null || member.Locales.Contains(locale));

    private string InterfaceName(bool isRaw, string path)
        => typePrefix + (isRaw ? rawInterface : target.Name) + path;

    private void OpenBlock()
    {
        writer.WriteLine("{");
        ++writer.Indent;
    }

    private void CloseBlock()
    {
        --writer.Indent;
        writer.WriteLine("}");
    }

    private static string Literal(string value)
        => SymbolDisplay.FormatLiteral(value, quote: true);
}